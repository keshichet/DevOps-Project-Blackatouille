// Robin Allanigue - DELETE recipe (backend)
// Route: DELETE /delete-recipe/:id   Body: { "confirmName": "<exact recipe name>" }
//
// Success : 200 { message, recipe (the deleted one), remaining }
// Errors  : 400 invalid ID / missing confirmation / confirmation does not match
//           403 recipe is locked
//           404 recipe not found
//           500 unexpected server error (e.g. unreadable JSON file)

const fs = require('fs').promises;
const path = require('path');

// Same JSON data store as Create and Update (template is the fallback if recipes.json is missing)
const RECIPES_FILE = path.join(__dirname, 'recipes.json');
const TEMPLATE_FILE = path.join(__dirname, 'recipes.template.json');

// IDs are generated by models/Recipe.js as a string of digits (timestamp + 3 random digits)
const ID_PATTERN = /^\d+$/;

// JSON data store helpers
async function readRecipes() {
   try {
      const data = await fs.readFile(RECIPES_FILE, 'utf8');
      return JSON.parse(data);
   } catch (err) {
      if (err.code === 'ENOENT') {
         const templateData = await fs.readFile(TEMPLATE_FILE, 'utf8');
         return JSON.parse(templateData);
      }
      throw err;
   }
}

async function writeRecipes(recipes) {
   await fs.writeFile(RECIPES_FILE, JSON.stringify(recipes, null, 2), 'utf8');
}

// Trim, collapse inner spaces and ignore case, so "  chicken   RICE " matches "Chicken Rice"
function normaliseName(value) {
   return String(value).trim().replace(/\s+/g, ' ').toLowerCase();
}

// Request validation (runs BEFORE the data store is read)
// Returns an error message string, or null if the request is well-formed
function validateDeleteRequest(id, body) {
   if (typeof id !== 'string' || !ID_PATTERN.test(id)) {
      return 'Invalid recipe ID: it must contain digits only';
   }
   const confirmName = (body || {}).confirmName;
   if (typeof confirmName !== 'string' || confirmName.trim() === '') {
      return 'Please type the recipe name to confirm the deletion';
   }
   return null;
}

// DELETE /delete-recipe/:id
async function deleteRecipe(req, res) {
   try {
      const id = req.params.id;

      // 1. Reject malformed requests without touching the JSON file
      const error = validateDeleteRequest(id, req.body);
      if (error) {
         return res.status(400).json({ message: error });
      }

      // 2. Read the JSON data store
      const recipes = await readRecipes();

      // 3. The recipe must exist
      const index = recipes.findIndex((r) => String(r.id) === id);
      if (index === -1) {
         return res.status(404).json({
            message: 'Recipe not found. It may have already been deleted.',
         });
      }
      const recipe = recipes[index];

      // 4. Business rule: locked recipes are protected and can never be deleted
      if (recipe.locked === true) {
         return res.status(403).json({
            message: '"' + recipe.name + '" is locked and cannot be deleted',
         });
      }

      // 5. The typed confirmation must match this recipe's name (guards against deleting the wrong one)
      if (normaliseName(req.body.confirmName) !== normaliseName(recipe.name)) {
         return res.status(400).json({
            message:
               'Confirmation does not match the recipe name "' +
               recipe.name +
               '"',
         });
      }

      // 6. Remove it and save the JSON data store
      recipes.splice(index, 1);
      await writeRecipes(recipes);

      return res.status(200).json({
         message: '"' + recipe.name + '" was deleted successfully',
         recipe: recipe,
         remaining: recipes.length,
      });
   } catch (error) {
      console.error(error);
      return res.status(500).json({ message: error.message });
   }
}

module.exports = { deleteRecipe };
